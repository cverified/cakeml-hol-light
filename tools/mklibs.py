"""the HOL4 library theories that the scope needs, in an order in
   which every one comes after the ones it needs

  python3 -I tools/mklibs.py          say what would change
  python3 -I tools/mklibs.py -w       write tools/libs.txt

tools/libs.txt is the first part of the porting order
(tools/db.py): the theories of HOL4 itself that CakeML uses, of
which the port takes what CakeML needs.  tools/closure2.py writes
tools/ext2.txt, the names outside cakeml-src that the scope
reaches; this finds the source of each in hol4-src and puts the
ones that are not there yet into libs.txt.

Three kinds of name are left out:

- an SML library, which tools/deps.py sees because a `Libs` entry
  `fooLib` brings the grammar of a theory `foo`: eight of them
  (basisFunctions, cfTacticsBase, cv_trans, basicCompute,
  addPrettyPrinters, astToSexpr, inlining, ag32_decompiler) have
  no Script at all and are tactics or tooling;
- a model of a machine (arm, arm8, mips, riscv, x64), which is
  generated by L3 and is 57,293 lines between them.  The port
  does with those what it already does with the encoders of the
  targets: the constants that CakeML names are declared
  (`cake_declare`, see ml/compiler/compiler.ml), and the model
  itself stays out;
- a theory that HOL Light itself has what CakeML uses of
  (tools/native.txt), which is where HOL4's own kernel and
  library go: bool, num, arithmetic, list, pred_set, words;
- a theory ml/lib already has a file of.
"""
import os, re, sys, collections

T = os.path.dirname(os.path.abspath(__file__)) + '/'
H = T + '../hol4-src/'
ML = T + '../ml/lib/'
MODELS = {'arm', 'arm8', 'mips', 'riscv', 'x64'}
want = [l.strip() for l in open(T + 'ext2.txt') if l.strip()]
have = [l.split('\t')[0] for l in open(T + 'libs.txt') if l.strip()]
native = set(l.strip() for l in open(T + 'native.txt')
             if l.strip() and not l.startswith('#'))
src = {}
for dp, dn, fn in os.walk(H):
  if '/.git' in dp: continue
  for f in fn:
    if f.endswith('Script.sml'): src[f[:-10]] = os.path.join(dp, f)
deps = {}
for t, p in src.items():
  s = open(p, encoding='utf-8', errors='replace').read()
  a = []
  for m in re.finditer(r'^Ancestors\b(.*?)(?=^\S|\Z)', s, re.M | re.S):
    b = re.sub(r'\[[^\]]*\]', '', m.group(1))
    a += re.sub(r'\(\*.*?\*\)', '', b, flags=re.S).split()
  for m in re.finditer(r'^\s*(?:val _ = )?open\s+([^;]*);', s, re.M):
    a += [w[:-6] for w in m.group(1).split() if w.endswith('Theory')]
  deps[t] = sorted(set(a))
new, lib, model, sml = [], [], [], []
for t in want:
  if t in have or t in native: continue
  if t in MODELS: model.append(t); continue
  if t not in src: sml.append(t); continue
  if os.path.exists(ML + t + '.ml'): lib.append(t); continue
  new.append(t)
print('%d names outside cakeml-src; %d of them already settled'
      % (len(want), len(want) - len(new) - len(model) - len(sml)
         - len(lib)))
print('  %d SML libraries, no theory: %s' % (len(sml), ' '.join(sorted(sml))))
print('  %d machine models, declared not ported: %s'
      % (len(model), ' '.join(sorted(model))))
print('  %d ml/lib has but libs.txt does not name: %s'
      % (len(lib), ' '.join(sorted(lib))))
print('  %d to add: %s' % (len(new), ' '.join(sorted(new))))
# the new ones after the ones they need, after everything there
order, seen = [], set(have)
def visit(t, stack=()):
  if t in seen or t not in set(new): return
  if t in stack: print('CYCLE', t); return
  seen.add(t)
  for a in deps.get(t, []): visit(a, stack + (t,))
  order.append(t)
for t in sorted(new): visit(t)
print('\norder of the new ones:', ' '.join(order))
s = ''.join('%s\t%s\n' % (t, os.path.relpath(src[t], H)) for t in order)
if '-w' in sys.argv:
  open(T + 'libs.txt', 'a').write(s)
  print('appended %d lines to libs.txt' % len(order))
else:
  print('\n' + s + '(dry run; -w appends)')
