"""write an OCaml file that parses every termination relation of
   the port, so that a session says which of them does not parse,
   does not typecheck or has a free variable in it

     python3 -I tools/relcheck.py > tmp/relcheck.ml
     repl-step <session> '#use ".../tmp/relcheck.ml";;'

   A relation that does not typecheck is an error that the file it
   is in does not survive, so this is a check to run after a change
   to the port and before a run.  A free variable in it only makes
   the measure fail (the strategies then guess one), but it means
   that the relation of HOL4 is of no use."""
import os, re, sys

T = os.path.dirname(os.path.abspath(__file__))
ML = os.path.join(T, '..', 'ml')

def relations():
  """(file, line, relation) of every cake_define_wf of the port"""
  out = []
  for root, _, fs in os.walk(ML):
    for f in sorted(fs):
      if not f.endswith('.ml'): continue
      p = os.path.join(root, f)
      lines = open(p).read().split('\n')
      for i, l in enumerate(lines):
        if not (l.endswith('cake_define_wf') or
                l.endswith('cake_define_list_wf')): continue
        # the relation is the quotation that follows
        txt = []
        j = i + 1
        while j < len(lines):
          txt.append(lines[j])
          if lines[j].count('`') >= (2 if j == i + 1 else 1): break
          j += 1
        rel = '\n'.join(txt).strip()
        if rel.startswith('`'): rel = rel[1:]
        if rel.endswith('`'): rel = rel[:-1]
        out.append((os.path.relpath(p, ML), i + 1, rel))
  return out

print('(* generated by tools/relcheck.py *)')
print('let relcheck_bad = ref 0;;')
print('let relcheck nm s =')
print('  match (try Some(parse_term s)')
print('         with Failure e -> (Printf.printf "%s: %s\\n%!" nm e;')
print('                            None)) with')
print('    None -> incr relcheck_bad')
print('  | Some t ->')
print('      let fv = frees t in')
print('      if fv <> [] then')
print('        (incr relcheck_bad;')
print('         Printf.printf "%s: free %s\\n%!" nm')
print('           (String.concat ", " (map (fst o dest_var) fv)));;')
for f, n, rel in relations():
  s = rel.replace('\\', '\\\\').replace('"', '\\"')
  s = ' '.join(s.split())
  print('relcheck "%s:%d" "%s";;' % (f, n, s))
print('Printf.printf "%d relations to look at\\n%!" (!relcheck_bad);;')
