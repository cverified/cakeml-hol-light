"""write ml/CHEATS.md from tmp/cheats.txt, the definitions that the
   first pass assumes instead of making them"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import defsites

C = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = [l.strip() for l in open(C + '/tmp/cheats.txt') if l.strip()]
# the file that defines each of them, and the phrase in it
sites = defsites.sites()


def not_loaded():
  """the theories the run says nothing about: one that failed, one
     whose ancestor failed (it is missing what that one defines)
     and one the run never reached"""
  sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
  import db as dbmod
  db = dbmod.Db()
  thy_of = {}
  for thy, _, _ in dbmod.load_order():
    try: thy_of[db.mlpath_of(thy)] = thy
    except Exception: pass
  bad, seen = set(), set()
  try: rows = open(C + '/tmp/cs.out')
  except OSError: return {}, {}
  for l in rows:
    rel = l.split()[0] if l.split() else ''
    if rel in thy_of:
      seen.add(thy_of[rel])
      if 'Exception' in l or 'Error' in l: bad.add(thy_of[rel])
  bad |= {t for t in db.kind_of_thy if t not in seen}
  bad = {t for t in db.kind_of_thy if (db.ancestors(t) | {t}) & bad}
  return bad, thy_of


def old_rows():
  """the table as it stands, so that a definition of a file the run
     says nothing about keeps the row it had: a run in which a file
     did not load counts no cheat of it, and the port reads this
     table to know which definitions it cannot make"""
  out = []
  try: rows = open(C + '/ml/CHEATS.md')
  except OSError: return out
  for l in rows:
    m = re.match(r'\| `([^`]*)` \| `([^`]*)` \| (.*) \|', l)
    if m: out.append((m.group(1), m.group(2), m.group(3).strip()))
  return out


BAD, THY_OF = not_loaded()
KEPT = {}
if BAD:
  have = set(names)
  for nm, f, w in old_rows():
    if nm in have: continue
    # the file of a name the table has no file for (foo_ind) is
    # the file of the definition it comes with
    f = f or (sites[nm[:-4]][0] if nm.endswith('_ind')
              and nm[:-4] in sites else sites.get(nm, ('',))[0])
    if THY_OF.get(f) in BAD:
      names.append(nm)
      KEPT[nm] = (f, w)
where = {nm: sites[nm][0] for nm in names if nm in sites}
phrase = {nm: sites[nm][1] for nm in names if nm in sites}
for nm, (f, w) in KEPT.items():
  if f: where[nm] = f
with open(C + '/ml/CHEATS.md', 'w') as out:
  out.write('# What the port assumes\n\n')
  try:
    nax = int(open(C + '/tmp/axioms.txt').read().strip())
  except Exception:
    nax = None
  out.write('Generated by `tools/bin/cheats`.  Every line below\n'
            'is something the port assumes instead of deriving,\n'
            'and the file that holds it says so at the call site:\n'
            '`assume_definition` where the definition itself is\n'
            'assumed, a way whose name ends in `_cheat` where only\n'
            'its termination is, and a `<name>_ind` line where the\n'
            'induction theorem of a definition is assumed with it.\n'
            'A definition that is assumed as a whole is one axiom;\n'
            'one that is assumed clause by clause (its clauses did\n'
            'not fit together, which is a bug of the port) is one\n'
            'axiom per clause.  A declared constant is no axiom: it\n'
            'has an implicit definition, which says nothing about\n'
            'its value.\n\n')
  if nax is not None:
    out.write('`length (axioms ())` is %d: the three axioms of HOL\n'
              'Light, one for every theorem of phase two whose\n'
              'proof is still a cheat, and the rest for the %d\n'
              'definitions below.\n\n'
              % (nax, len(names)))
  if KEPT:
    out.write('Of the definitions below, %d are in a file that did\n'
              'not load in this run, so what the run counts says\n'
              'nothing about them and they keep the row they had.\n\n'
              % len(KEPT))
  # why each of them is assumed, where the library layer says it
  why = {}
  try:
    for l in open(C + '/tmp/why.txt'):
      if '\t' in l:
        n, w = l.rstrip('\n').split('\t', 1)
        why[n] = w
  except Exception:
    pass
  for n, (_, w) in KEPT.items(): why[n] = w
  # the three kinds, of which only the last is work to do: a
  # definition whose termination is assumed is made (the constant
  # is real and so are its clauses), and a declared constant is
  # one whose value HOL4 computes with ML code
  import collections
  kind = collections.Counter()
  for nm in names:
    w = why.get(nm, '')
    kind['termination' if w.startswith('termination') else
         'declared' if w.startswith('declared') else
         'not made'] += 1
  out.write('Of these %d definitions\n\n'
            '- %d have only their **termination** assumed, so the\n'
            '  constant, its type and its clauses are the real ones;\n'
            '- %d are a constant that is **declared** without a\n'
            '  value, because HOL4 computes the value with ML code:\n'
            '  the constant has an implicit definition, which says\n'
            '  nothing about it and adds no axiom (PENDING.md);\n'
            '- %d are assumed for another reason, which the list\n'
            '  below names (the equation of a tail recursion that\n'
            '  HOL4 proves with its `mc_tailrecLib`, say).\n\n'
            % (len(names), kind['termination'], kind['declared'],
               kind['not made']))
  # the reasons, with how many definitions each of them has:
  # that is what the next round has to attack
  cnt = collections.Counter(why.get(nm, '') or '(not recorded)'
                            for nm in names)
  out.write('Why they are assumed:\n\n')
  for w, n in cnt.most_common():
    out.write('- %d: %s\n' % (n, w[:66]))
  out.write('\n')
  out.write('| definition | file | why |\n|---|---|---|\n')
  for nm in names:
    w = why.get(nm, '')
    w = w.replace('|', '/')[:60]
    out.write('| `%s` | `%s` | %s |\n' % (nm, where.get(nm, ''), w))
  out.write('\n%d definitions.\n' % len(names))
print('wrote ml/CHEATS.md (%d)' % len(names))
# the reasons, so that the next round knows what to attack
import collections
c = collections.Counter(why.get(nm, '') for nm in names)
for w, n in c.most_common(12):
  print('%5d %s' % (n, (w or '(no reason recorded)')[:60]))
