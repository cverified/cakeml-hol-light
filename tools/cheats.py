"""write ml/CHEATS.md from tmp/cheats.txt, the definitions that the
   first pass assumes instead of making them"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import defsites

C = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = [l.strip() for l in open(C + '/tmp/cheats.txt') if l.strip()]
# the file that defines each of them, and the phrase in it
sites = defsites.sites()
where = {nm: sites[nm][0] for nm in names if nm in sites}
phrase = {nm: sites[nm][1] for nm in names if nm in sites}
with open(C + '/ml/CHEATS.md', 'w') as out:
  out.write('# The definitions that the first pass assumes\n\n')
  try:
    nax = int(open(C + '/tmp/axioms.txt').read().strip())
  except Exception:
    nax = None
  out.write('Generated by `tools/bin/cheats`.  The first pass of\n'
            'the port states these definitions as axioms instead of\n'
            'deriving them, because HOL Light\'s machinery does not\n'
            'find the form or the termination argument that HOL4\n'
            'has.  A definition that is assumed as a whole is one\n'
            'axiom; one that is assumed clause by clause (its\n'
            'clauses did not fit together, which is a bug of the\n'
            'port) is one axiom per clause.\n\n')
  if nax is not None:
    out.write('`length (axioms ())` is %d: the three axioms of HOL\n'
              'Light and %d for the %d definitions below.\n\n'
              % (nax, nax - 3, len(names)))
  # why each of them is assumed, where the library layer says it
  why = {}
  try:
    for l in open(C + '/tmp/why.txt'):
      if '\t' in l:
        n, w = l.rstrip('\n').split('\t', 1)
        why[n] = w
  except Exception:
    pass
  # the reasons, with how many definitions each of them has:
  # that is what the next round has to attack
  import collections
  cnt = collections.Counter(why.get(nm, '') or '(not recorded)'
                            for nm in names)
  out.write('Why they are assumed:\n\n')
  for w, n in cnt.most_common():
    out.write('- %d: %s\n' % (n, w[:66]))
  out.write('\n')
  out.write('| definition | file | why |\n|---|---|---|\n')
  for nm in names:
    w = why.get(nm, '')
    w = w.replace('|', '/')[:60]
    out.write('| `%s` | `%s` | %s |\n' % (nm, where.get(nm, ''), w))
  out.write('\n%d definitions.\n' % len(names))
print('wrote ml/CHEATS.md (%d)' % len(names))
# the reasons, so that the next round knows what to attack
import collections
c = collections.Counter(why.get(nm, '') for nm in names)
for w, n in c.most_common(12):
  print('%5d %s' % (n, (w or '(no reason recorded)')[:60]))
