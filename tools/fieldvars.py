"""the variables of a statement whose name the port overloads with
   a record accessor

HOL4 has no constant of the name of a record field (`r.stack` is
syntax there and a bare `stack` is a variable), and the port
overloads the accessors of a field that several records have with
the name of the field.  A statement that uses such a name for a
variable of its own therefore says the type of that variable, and
this is the table of those types.

VARS is read by tools/port.py, which annotates the first
occurrence of each variable.  READ are the statements whose
variable has a type with a variable of its own, which cannot be
said in the statement (the annotation would not unify): those are
read with the overloads of the field names taken away
(`cake_as_vars`).

A statement that needs an entry and has none does not typecheck,
and the file says so where it loads.  To find the entry, read the
statement in a session that has the file's needs loaded:

    let tm = cake_as_vars (fun () -> `<the statement>`);;
    map (fun v -> fst(dest_var v), type_of v) (frees tm);;

and take the variables whose names the interface overloads."""

